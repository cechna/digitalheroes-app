-- Storage Bucket Setup for Digital Heroes Materials
-- Bucket: 'materials' (private bucket)
-- ==============================================================================

-- 1. Create the private bucket if it doesn't exist
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
    'materials',
    'materials',
    FALSE, -- PRIVATE BUCKET: downloads require signed URLs or authenticated RLS
    26214400, -- 25 MB max limit
    ARRAY[
        'application/pdf',
        'application/msword',
        'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
        'application/vnd.ms-excel',
        'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
        'application/vnd.ms-powerpoint',
        'application/vnd.openxmlformats-officedocument.presentationml.presentation',
        'application/zip',
        'application/x-zip-compressed',
        'image/png',
        'image/jpeg',
        'image/webp'
    ]
)
ON CONFLICT (id) DO UPDATE SET
    public = FALSE,
    file_size_limit = 26214400;

-- 2. Storage Policies: Allow admins and organizers to upload to 'materials'
CREATE POLICY "materials_upload_policy"
ON storage.objects FOR INSERT TO authenticated
WITH CHECK (
    bucket_id = 'materials' AND (
        public.is_admin() OR
        EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role IN ('admin', 'organizer'))
    )
);

